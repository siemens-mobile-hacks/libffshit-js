// Generates src/filesystem/codepages.ts from glibc's iconv, which the C++ library converts SGOLD
// names with: for each codepage, the code point of every byte, or -1 where iconv rejects the byte.
//
//   gcc -O2 scripts/gen-codepages.c -o gen-codepages && ./gen-codepages > src/filesystem/codepages.ts
//
// Only stateless single-byte codepages that encode exactly what they decode are emitted. glibc's
// CP1255 and CP1258 compose combining marks, so they are not tables and are left out.

